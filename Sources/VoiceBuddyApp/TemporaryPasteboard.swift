import AppKit

/// Owns a temporary pasteboard value until it is restored or replaced externally.
final class TemporaryPasteboard {
    private static var activeOriginalItemsByBoard: [String: [[(NSPasteboard.PasteboardType, Data)]]] = [:]
    private let board: NSPasteboard
    private let savedItems: [[(NSPasteboard.PasteboardType, Data)]]
    private var ownedChangeCount: Int

    init(board: NSPasteboard = .general) {
        self.board = board
        let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
        let autoGenType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
        let boardKey = board.name.rawValue

        let hasTransient = board.pasteboardItems?.contains { item in
            item.types.contains(transientType) || item.types.contains(autoGenType)
        } ?? false

        if hasTransient, let activeSaved = TemporaryPasteboard.activeOriginalItemsByBoard[boardKey] {
            self.savedItems = activeSaved
        } else {
            let captured = (board.pasteboardItems ?? []).map { item in
                item.types.compactMap { type in item.data(forType: type).map { (type, $0) } }
            }
            self.savedItems = captured
            TemporaryPasteboard.activeOriginalItemsByBoard[boardKey] = captured
        }
        self.ownedChangeCount = board.changeCount
    }

    func write(_ text: String, sensitive: Bool) -> Bool {
        board.clearContents()
        ownedChangeCount = board.changeCount
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        item.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.TransientType"))
        item.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"))
        if sensitive {
            item.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"))
        }
        let success = board.writeObjects([item])
        ownedChangeCount = board.changeCount
        return success
    }

    func owns(_ text: String) -> Bool {
        board.changeCount == ownedChangeCount && board.string(forType: .string) == text
    }

    @discardableResult
    func restore() -> Bool {
        let boardKey = board.name.rawValue
        guard board.changeCount == ownedChangeCount else {
            TemporaryPasteboard.activeOriginalItemsByBoard.removeValue(forKey: boardKey)
            return false
        }
        board.clearContents()
        let items: [NSPasteboardItem] = savedItems.compactMap { entries in
            guard !entries.isEmpty else { return nil }
            let item = NSPasteboardItem()
            for (type, data) in entries { item.setData(data, forType: type) }
            return item
        }
        let success = items.isEmpty || board.writeObjects(items)
        ownedChangeCount = -1
        TemporaryPasteboard.activeOriginalItemsByBoard.removeValue(forKey: boardKey)
        return success
    }
}
